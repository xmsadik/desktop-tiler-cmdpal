using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using DesktopTiler.Core.VirtualDesktops;
using DesktopTiler.Core.Windows;
using Microsoft.CommandPalette.Extensions;
using Microsoft.CommandPalette.Extensions.Toolkit;

namespace DesktopTiler;

/// <summary>
/// The "Desktops" Dock band content: one <see cref="ListItem"/> per virtual desktop, title
/// "1"/"2"/..., subtitle = the desktop's name if it has one.
/// Clicking an item switches to that desktop. Each item's icon is a filled square if the desktop
/// has at least one app window on it, an outlined square if it's empty, with a blue ring around
/// it on the active desktop, whose title is also marked "●" with a bold number (no icon at all
/// if occupancy couldn't be determined). Where the Dock shows no desktop names (Compact size,
/// labels off, or "Show desktop names" off) the number is drawn inside the square instead and the
/// title is left empty, so the buttons are icon-only and narrower. With a Compact Dock, hovering a button also lists that
/// desktop's windows (the subtitle's extra lines, see DesktopWindowGroups.TooltipSubtitle and
/// DockLayoutProbe); <see cref="WindowEventWatcher"/> keeps it live as windows come and go.
///
/// Also usable as an ordinary <see cref="ListPage"/> (so it can be opened as a page, not just as
/// a Dock band), which is why it implements <see cref="ListPage.RaiseItemsChanged"/> semantics.
/// The provider additionally listens to <see cref="Refreshed"/> to keep the separately-created
/// <c>WrappedDockItem.Items</c> array (the actual Dock band content) in sync, since
/// RaiseItemsChanged only notifies consumers of this page, not of the Dock band wrapper.
/// </summary>
internal sealed partial class DesktopsPage : ListPage, IDisposable
{
    // Square filled = desktop has app windows, outlined = empty; the active desktop's square also
    // gets a blue ring. PNGs (generated by scripts/make-dock-icons.py) because a glyph can't carry
    // the second colour; one per Windows theme.
    private static readonly IconInfo OccupiedIcon = DockIcon("occupied");
    private static readonly IconInfo EmptyIcon = DockIcon("empty");
    private static readonly IconInfo OccupiedActiveIcon = DockIcon("occupied-active");
    private static readonly IconInfo EmptyActiveIcon = DockIcon("empty-active");

    // Highest desktop number with a numbered icon (keep in sync with MAX_NUMBER in
    // scripts/make-dock-icons.py); desktops past it keep the plain icon and a "21" title.
    private const int MaxNumberedIcon = 20;
    private static readonly Dictionary<string, IconInfo> NumberedIcons = [];

    private readonly VdComClient _vdClient;
    private readonly RegistryDesktopReader _registryReader;
    private readonly SettingsManager _settingsManager;
    private readonly WindowEventWatcher _windowWatcher;
    private readonly DockLayoutProbe _dockLayout;

    // The occupancy set the Dock last rendered (written by GetItems). Window events recompute it
    // and only refresh the band when it actually differs, so the constant churn of unrelated
    // windows showing/hiding doesn't redraw the band. Replaced, never mutated.
    private volatile Dictionary<Guid, List<nint>>? _lastWindows;

    // The band's items, one per desktop id, reused across refreshes (see GetItems). GetItems runs
    // on host threads as well as the registry poll thread, hence the lock.
    private readonly Dictionary<Guid, ListItem> _items = [];
    private readonly object _itemsGate = new();

    public DesktopsPage(VdComClient vdClient, RegistryDesktopReader registryReader, SettingsManager settingsManager, WindowEventWatcher windowWatcher, DockLayoutProbe dockLayout)
    {
        _vdClient = vdClient;
        _registryReader = registryReader;
        _settingsManager = settingsManager;
        _windowWatcher = windowWatcher;
        _dockLayout = dockLayout;

        Id = "DesktopTiler.page.desktops";
        Title = "Desktops";
        Name = "Desktops";
        Icon = new IconInfo(""); // Desktop-ish glyph fallback; keep simple for Phase 1.
        PlaceholderText = "Switch virtual desktop";

        _registryReader.Changed += OnRegistryChanged;
        _settingsManager.ShowDesktopNamesChanged += OnShowDesktopNamesChanged;
        _windowWatcher.Changed += OnWindowsChanged;
        _dockLayout.Changed += OnDockLayoutChanged;
    }

    /// <summary>Raised whenever the item set has changed (registry poll saw a change, a switch we just
    /// performed, or the "Show desktop names" setting changed), in addition to the standard
    /// RaiseItemsChanged.</summary>
    public event EventHandler? Refreshed;

    public void Dispose()
    {
        _registryReader.Changed -= OnRegistryChanged;
        _settingsManager.ShowDesktopNamesChanged -= OnShowDesktopNamesChanged;
        _windowWatcher.Changed -= OnWindowsChanged;
        _dockLayout.Changed -= OnDockLayoutChanged;
    }

    /// <summary>Called by the switch command right after a successful switch, since the COM
    /// "current desktop" can change without the registry key changing in lockstep.</summary>
    public void NotifyAfterSwitch() => Refresh();

    public override IListItem[] GetItems()
    {
        IReadOnlyList<DesktopInfo> desktops;
        try
        {
            desktops = _registryReader.ReadDesktops();
        }
        catch (Exception ex)
        {
            // Called directly by the host (not just via Refresh()), so this must never throw -
            // an unhandled exception here would crash the host, not just this page.
            SpikeLog.WriteLine($"DesktopsPage.GetItems: ReadDesktops failed: {ex}");
            return [new ListItem { Title = "Desktop list unavailable" }];
        }

        if (desktops.Count == 0)
        {
            // A fresh profile that's never opened Task View has no VirtualDesktops registry key
            // at all, even though Windows always has (at least) one desktop - fall back to the
            // COM enumeration for that single desktop (no name) before giving up.
            desktops = DesktopListReader.FallbackToVdComClient(_vdClient);
            if (desktops.Count == 0)
            {
                return [new ListItem { Title = "No virtual desktops found" }];
            }
        }

        Guid currentId;
        try
        {
            currentId = _vdClient.GetCurrentIdAsync().WaitOrTimeout(TaskTimeoutExtensions.DefaultTimeout);
        }
        catch (UnsupportedBuildException)
        {
            return [new ListItem { Title = "Unsupported Windows build for desktop switching" }];
        }
        catch (Exception)
        {
            // Includes ExplorerNotRespondingException: no active-desktop marker is a reasonable
            // degrade rather than failing the whole list over a call that timed out.
            currentId = Guid.Empty;
        }

        var windows = ComputeDesktopWindows();
        _lastWindows = windows;

        // The window list rides on extra subtitle lines, which only stay out of sight (and so
        // only reach the tooltip) while the Dock hides subtitles - see DockLayoutProbe.
        var windowListInTooltip = _dockLayout.SubtitlesHidden;

        var items = new IListItem[desktops.Count];
        lock (_itemsGate)
        {
            for (var i = 0; i < desktops.Count; i++)
            {
                var desktop = desktops[i];
                var number = i + 1;
                var isActive = desktop.Id == currentId;

                var onDesktop = windows is not null && windows.TryGetValue(desktop.Id, out var list) ? list : null;
                var name = _settingsManager.ShowDesktopNames ? desktop.Name : null;

                // Where the Dock shows no desktop names, the number moves into the icon and the
                // title stays empty: an icon-only button lets the Dock drop the gap between icon
                // and label, so the band gets narrower.
                var numbered = windows is not null && number <= MaxNumberedIcon && (windowListInTooltip || !_settingsManager.ShowDesktopNames);

                // The active desktop: blue ring on the icon, plus "●" and a bold number in the
                // title (the Dock can't style its labels, so bold Unicode digits stand in for a
                // bold font).
                var digits = number.ToString(CultureInfo.InvariantCulture);
                var title = numbered ? string.Empty : isActive ? "●" + BoldDigits(digits) : digits;

                // One long-lived item per desktop, updated in place: the Dock keeps the item it
                // already shows when the band is refreshed and only picks up property changes,
                // so an icon-only change (the active ring moving, a desktop becoming empty) is
                // lost if a new item is handed over instead. The setters raise PropertyChanged.
                if (!_items.TryGetValue(desktop.Id, out var item))
                {
                    item = new ListItem(new SwitchDesktopCommand(_vdClient, desktop.Id, this));
                    _items[desktop.Id] = item;
                }

                // An empty item title falls back to the command name, which would put "Desktop N"
                // back on an icon-only button - so a numbered button's command has no name either
                // (its tooltip still names the desktop, see below).
                ((SwitchDesktopCommand)item.Command!).Name = numbered ? string.Empty : $"Desktop {number}";
                item.Title = title;
                item.Icon = windows is null ? null : numbered ? NumberedIcon(number, onDesktop is not null, isActive) : IconFor(onDesktop is not null, isActive);

                // The subtitle's first line is the label (the desktop name); the window titles on
                // the lines after it only show up in the hover tooltip (see DesktopWindowGroups).
                // With no title, that first line also names the desktop, since the tooltip
                // otherwise wouldn't say which one it is.
                var header = numbered
                    ? string.IsNullOrEmpty(name) ? $"Desktop {number}" : $"Desktop {number} · {name}"
                    : name;
                item.Subtitle = windowListInTooltip
                    ? DesktopWindowGroups.TooltipSubtitle(header, onDesktop?.Select(WindowEnumerator.GetTitle).ToArray() ?? [])
                    : name ?? string.Empty;
                items[i] = item;
            }

            // Forget removed desktops.
            foreach (var stale in _items.Keys.Except(desktops.Select(d => d.Id)).ToArray())
            {
                _items.Remove(stale);
            }
        }

        return items;
    }

    /// <summary>"12" -> "𝟭𝟮": ASCII digits mapped to MATHEMATICAL SANS-SERIF BOLD DIGIT ZERO
    /// (U+1D7EC) onwards, which read as bold digits in the Dock's sans-serif font.</summary>
    internal static string BoldDigits(string digits)
    {
        var sb = new System.Text.StringBuilder(digits.Length * 2);
        foreach (var c in digits)
        {
            sb.Append(c is >= '0' and <= '9' ? char.ConvertFromUtf32(0x1D7EC + (c - '0')) : c.ToString());
        }

        return sb.ToString();
    }

    private static IconInfo IconFor(bool occupied, bool active) => (occupied, active) switch
    {
        (true, true) => OccupiedActiveIcon,
        (true, false) => OccupiedIcon,
        (false, true) => EmptyActiveIcon,
        (false, false) => EmptyIcon,
    };

    private static IconInfo DockIcon(string state) =>
        IconHelpers.FromRelativePaths($@"Assets\Dock\desktop-{state}-light.png", $@"Assets\Dock\desktop-{state}-dark.png");

    /// <summary>The square with the desktop number inside, used where the Dock shows no desktop
    /// names (Assets\Dock\Numbered, generated by scripts/make-dock-icons.py for 1..MaxNumberedIcon).
    /// Created once per number and state and reused, like the plain icons.</summary>
    private static IconInfo NumberedIcon(int number, bool occupied, bool active)
    {
        var state = (occupied ? "occupied" : "empty") + (active ? "-active" : string.Empty);
        var key = $"{number}-{state}";
        lock (NumberedIcons)
        {
            if (!NumberedIcons.TryGetValue(key, out var icon))
            {
                icon = IconHelpers.FromRelativePaths(
                    $@"Assets\Dock\Numbered\desktop-{key}-light.png",
                    $@"Assets\Dock\Numbered\desktop-{key}-dark.png");
                NumberedIcons[key] = icon;
            }

            return icon;
        }
    }

    private void OnRegistryChanged(object? sender, EventArgs e) => Refresh();

    private void OnShowDesktopNamesChanged(object? sender, EventArgs e) => Refresh();

    private void OnDockLayoutChanged(object? sender, EventArgs e) => Refresh();

    private void OnWindowsChanged(object? sender, EventArgs e)
    {
        var windows = ComputeDesktopWindows();
        var last = _lastWindows;
        if (windows is not null && last is not null && DesktopWindowGroups.SameMembership(windows, last))
        {
            return;
        }

        Refresh();
    }

    /// <summary>The app windows on each desktop (front first), keyed by desktop id; a desktop with
    /// none has no entry. Null if that couldn't be determined (logged; the band then shows no
    /// occupancy icons and no window list in the tooltip).</summary>
    private Dictionary<Guid, List<nint>>? ComputeDesktopWindows()
    {
        try
        {
            using var timing = SpikeLog.Timed("DesktopsPage.ComputeDesktopWindows");
            var ownPid = Environment.ProcessId;
            var handles = WindowEnumerator.EnumerateZOrder(null)
                .Where(w => DesktopOccupancy.IsAppWindow(w, ownPid, WindowEnumerator.CmdPalImageName))
                .Select(w => w.Handle)
                .ToArray();
            var ids = _vdClient.GetWindowDesktopIdsAsync(handles).WaitOrTimeout(TaskTimeoutExtensions.DefaultTimeout);
            return DesktopWindowGroups.Group(handles, ids);
        }
        catch (Exception ex)
        {
            SpikeLog.WriteLine($"DesktopsPage.ComputeDesktopWindows failed: {ex.Message}");
            return null;
        }
    }

    /// <summary>Raises <see cref="RaiseItemsChanged"/> and <see cref="Refreshed"/>. Called from the
    /// registry poll thread (<see cref="OnRegistryChanged"/>) as well as
    /// straight off a command invocation (<see cref="NotifyAfterSwitch"/>); either way, an
    /// exception here (ours, a subscriber's, e.g. the provider re-reading items for the Dock band)
    /// must not crash the host - it's logged to SpikeLog and swallowed instead.</summary>
    private void Refresh()
    {
        try
        {
            RaiseItemsChanged();
            Refreshed?.Invoke(this, EventArgs.Empty);
        }
        catch (Exception ex)
        {
            SpikeLog.WriteLine($"DesktopsPage.Refresh failed: {ex}");
        }
    }
}
